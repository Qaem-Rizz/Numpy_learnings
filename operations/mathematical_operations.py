#every arithmetic operation can be performed in the numpy arrays such as addition, subtraction, multiplication, division, and more. Numpy also provides a wide range of mathematical functions that can be applied to arrays, such as trigonometric functions, exponential functions, and logarithmic functions. Additionally, numpy supports broadcasting, which allows for operations between arrays of different shapes and sizes.



import numpy as np
array = np.array([1, 2, 3, 4, 5])

print(array + 2) #output: [3 4 5 6 7] - adds 2 to each element of the array
print(array - 1) #output: [0 1 2 3 4] - subtracts 1 from each element of the array
print(array * 3) #output: [ 3  6  9 12 15] - multiplies each element of the array by 3
print(array / 2) #output: [0.5 1.  1.5 2.  2.5] - divides each element of the array by 2
print(array**2) #output: [ 1  4  9 16 25] - raises each element of the array to the power of 2


